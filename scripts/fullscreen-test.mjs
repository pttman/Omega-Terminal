import { _electron as electron } from 'playwright';
import { expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const {sshFixture}=createRequire(import.meta.url)('../tests/fixture.cjs');
const directory='test-results/fullscreen';fs.mkdirSync(directory,{recursive:true});
const fixture=await sshFixture();const checks=[],errors=[];let app;
try{
  const env={...process.env,PERSON_TEST:`fullscreen-${Date.now()}`,PERSON_TEST_EXIT:'1'};
  delete env.ELECTRON_RUN_AS_NODE;delete env.PERSON_DEV_URL;
  const packaged=process.argv.indexOf('--packaged');
  app=await electron.launch({...(packaged>=0?{executablePath:path.resolve(process.argv[packaged+1]),args:[]}:{args:['.']}),cwd:process.cwd(),env,timeout:30000});
  const page=await app.firstWindow();page.on('pageerror',error=>errors.push(error.message));
  const shell=page.locator('.app-shell');
  const native=()=>app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];return {fullscreen:w.isFullScreen(),maximized:w.isMaximized()};});
  const pure=async(count=1)=>{
    await expect(shell).toHaveClass(/terminal-immersive/);
    await expect(page.locator('.terminal-surface:visible')).toHaveCount(count);
    expect(await page.locator('.sidebar,.titlebar,.terminal-toolbar,.statusbar,.assistant,.pane-header,.composer-wrap,.terminal-search,.appearance-panel,.toast-stack,.login-message,.pane-divider').evaluateAll(elements=>elements.filter(element=>element.checkVisibility()).map(element=>element.className))).toEqual([]);
    const bounds=await page.locator('.pane-canvas').evaluate(element=>{const r=element.getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height,viewportWidth:innerWidth,viewportHeight:innerHeight};});
    expect(bounds.x).toBe(0);expect(bounds.y).toBe(0);expect(bounds.width).toBe(bounds.viewportWidth);expect(bounds.height).toBe(bounds.viewportHeight);
  };
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await page.locator('.window-controls button[title="最大化 / 还原"]').click();
  await expect.poll(native).toEqual({fullscreen:false,maximized:true});
  await expect(page.locator('.titlebar')).toBeVisible();await expect(shell).not.toHaveClass(/terminal-immersive/);
  await page.locator('.window-controls button[title="最大化 / 还原"]').click();
  checks.push('Homepage keeps its normal maximize controls and navigation');
  await page.locator('.local-card').click();
  await expect.poll(()=>page.evaluate(async()=>(await window.person.bootstrap()).sessions[0]?.ready),{timeout:25000}).toBeTruthy();
  await expect(page.locator('.sidebar')).toBeHidden();
  await page.getByRole('button',{name:'命令栏',exact:true}).click();
  await page.locator('.command-composer textarea').fill('kept draft');
  await page.getByRole('button',{name:'随行助手',exact:true}).click();
  await page.getByRole('button',{name:'查找输出',exact:true}).click();
  await page.locator('.window-controls button[title="全屏（F11 退出）"]').click();
  await expect.poll(native).toMatchObject({fullscreen:true});await pure();
  await expect(page.locator('.terminal-pane.focused .xterm-helper-textarea')).toBeFocused();
  await page.keyboard.type("Write-Output 'FULLSCREEN_OK'");await page.keyboard.press('Enter');
  await expect.poll(()=>page.locator('.terminal-pane:visible .xterm-rows>div').allTextContents(),{timeout:15000}).toContain('FULLSCREEN_OK');
  await expect.poll(()=>page.evaluate(async()=>(await window.person.bootstrap()).sessions[0].ready)).toBeTruthy();
  await page.keyboard.press('Escape');await pure();
  await page.screenshot({path:`${directory}/terminal-only.png`});
  checks.push('Connection button enters native fullscreen; only terminal fills the viewport, receives real input, and preserves Escape');
  await page.keyboard.press('F11');await expect(shell).not.toHaveClass(/terminal-immersive/);
  await expect(page.locator('.titlebar')).toBeVisible();await expect(page.locator('.sidebar')).toHaveCount(0);
  await expect(page.locator('.command-composer textarea')).toHaveValue('kept draft');await expect(page.locator('.assistant')).toBeVisible();
  await page.screenshot({path:`${directory}/restored.png`});
  checks.push('F11 restores navigation, assistant and command draft');
  await page.getByRole('button',{name:'关闭搜索',exact:true}).click();
  await page.getByRole('button',{name:'关闭助手',exact:true}).click();
  await page.getByRole('button',{name:'左右分屏（新建默认本地终端）'}).click();
  await expect(page.locator('.terminal-pane:visible')).toHaveCount(2);
  await page.keyboard.press('F11');await pure(2);await page.keyboard.press('F11');
  await expect(shell).not.toHaveClass(/terminal-immersive/);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].maximize());await pure(2);
  await page.keyboard.press('F11');await expect.poll(native).toEqual({fullscreen:false,maximized:false});
  checks.push('Split sessions stay visible; native maximize also hides all app chrome; F11 restores the window');
  await page.locator('.home-tab').click();
  await page.getByRole('button',{name:'新建连接',exact:true}).click();
  for(const [label,value] of [['服务器地址','127.0.0.1'],['端口',String(fixture.port)],['用户名','tester']])await page.getByLabel(label,{exact:true}).fill(value);
  await page.getByRole('button',{name:'保存并连接',exact:true}).click();
  await page.getByLabel('密码（交互认证可留空）').fill('fixture-password');await page.getByRole('button',{name:'直接连接',exact:true}).click();
  await page.getByRole('button',{name:'信任并连接',exact:true}).click();
  await expect(page.locator('.terminal-pane:visible .composer-footer')).toContainText('/home/test',{timeout:15000});
  await expect(page.locator('.sidebar')).toBeHidden();
  await page.keyboard.press('F11');await pure();
  await page.screenshot({path:`${directory}/ssh-only.png`});
  checks.push('Successful SSH connection has no sidebar; fullscreen also hides server login information and notices');
  await page.locator('.terminal-pane.focused .xterm-helper-textarea').evaluate(element=>{
    const data=new DataTransfer();data.setData('text/plain','echo first\necho second');element.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData:data}));
  });
  await expect(shell).not.toHaveClass(/terminal-immersive/);await expect(page.locator('.pane-confirm.wide')).toBeVisible();
  await page.locator('.pane-confirm.wide').getByRole('button',{name:'取消',exact:true}).click();
  await page.keyboard.press('F11');await pure();
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
  await expect(page.getByRole('dialog',{name:'准备离开工作区？'})).toBeVisible();
  await expect(shell).not.toHaveClass(/terminal-immersive/);
  await page.getByRole('button',{name:'继续使用',exact:true}).click();
  expect((await page.evaluate(()=>window.person.bootstrap())).sessions.every(session=>session.status==='connected')).toBe(true);
  checks.push('Multiline paste and native exit leave fullscreen for their confirmation; cancelling preserves all connections');
  expect(errors).toEqual([]);
  fs.writeFileSync(`${directory}/report.json`,JSON.stringify({passed:true,checks,errors},null,2));console.log(checks.map(check=>'PASS '+check).join('\n'));
}catch(error){console.error(error);if(app)try{await(await app.firstWindow()).screenshot({path:`${directory}/failure.png`});}catch{}fs.writeFileSync(`${directory}/report.json`,JSON.stringify({passed:false,checks,errors,error:String(error)},null,2));process.exitCode=1;}
finally{if(app)try{await app.evaluate(()=>{delete process.env.PERSON_TEST_EXIT;});await app.close();}catch{}await fixture.close();}
